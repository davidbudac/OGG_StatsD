#!/bin/bash
# First-start setup for GoldenGate replication on gvenzl/oracle-free.
# Runs once, from /container-entrypoint-initdb.d, before the healthcheck turns healthy.
set -Eeuo pipefail

# Enable archivelog mode and the logging GoldenGate needs
sqlplus -s / as sysdba <<'EOF'
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SYSTEM SET sga_max_size=1536m     SCOPE=SPFILE;
ALTER SYSTEM SET sga_target=1536m       SCOPE=SPFILE;
ALTER SYSTEM SET streams_pool_size=512m SCOPE=SPFILE;
SHUTDOWN IMMEDIATE;
STARTUP MOUNT;
ALTER DATABASE ARCHIVELOG;
ALTER DATABASE OPEN;
ALTER PLUGGABLE DATABASE ALL OPEN;
ALTER DATABASE FORCE LOGGING;
ALTER SYSTEM SET enable_goldengate_replication=TRUE SCOPE=BOTH;
ALTER DATABASE ADD SUPPLEMENTAL LOG DATA;
EXIT;
EOF

# Create the GoldenGate admin user and the HR sample schema in FREEPDB1
cd /opt/oracle/hr
sqlplus -s / as sysdba <<'EOF'
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE TABLESPACE gg_admin_data DATAFILE '/opt/oracle/oradata/FREE/FREEPDB1/ggadmin_data.dbf' SIZE 100M AUTOEXTEND ON NEXT 10M;
CREATE USER oggadmin IDENTIFIED BY "Welcome##123"
  DEFAULT TABLESPACE gg_admin_data QUOTA UNLIMITED ON gg_admin_data;
GRANT CREATE SESSION, RESOURCE, SELECT_CATALOG_ROLE, OGG_CAPTURE, OGG_APPLY TO oggadmin;
GRANT ALTER SYSTEM, ALTER USER, ALTER DATABASE, CREATE DATABASE LINK TO oggadmin;
GRANT SELECT ANY DICTIONARY, SELECT ANY TRANSACTION, LOCK ANY TABLE TO oggadmin;
GRANT INSERT ANY TABLE, UPDATE ANY TABLE, DELETE ANY TABLE TO oggadmin;
GRANT CREATE ANY TABLE, CREATE ANY INDEX, CREATE ANY CLUSTER, CREATE ANY INDEXTYPE,
      CREATE ANY OPERATOR, CREATE ANY PROCEDURE, CREATE ANY SEQUENCE, CREATE ANY TRIGGER,
      CREATE ANY TYPE, CREATE ANY VIEW TO oggadmin;
GRANT ALTER ANY TABLE, ALTER ANY INDEX, ALTER ANY CLUSTER, ALTER ANY INDEXTYPE,
      ALTER ANY OPERATOR, ALTER ANY PROCEDURE, ALTER ANY SEQUENCE, ALTER ANY TRIGGER,
      ALTER ANY TYPE TO oggadmin;
GRANT DATAPUMP_EXP_FULL_DATABASE, DATAPUMP_IMP_FULL_DATABASE TO oggadmin;

CREATE USER hr IDENTIFIED BY "Welcome##123" QUOTA UNLIMITED ON users;
GRANT DB_DEVELOPER_ROLE TO hr;
ALTER SESSION SET CURRENT_SCHEMA = hr;
ALTER SESSION SET NLS_LANGUAGE = American;
ALTER SESSION SET NLS_TERRITORY = America;
@@hr_create.sql
@@hr_populate.sql
@@hr_code.sql
EXIT;
EOF

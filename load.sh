#!/usr/bin/env bash
# Generates replication traffic so the dashboards have something to show.
#
#   ./load.sh [seconds] [rows_per_second]   steady load on both databases (default 600 s, 50 rows/s)
#   ./load.sh burst [rows]                   one large transaction on WEST (default 20000 rows;
#                                            ~100k overflows the 400 MB integrated-apply memory and hangs RWEST)
#   ./load.sh stop                           kill running load sessions on both databases
#
# Replication is bidirectional, so each database only touches its own rows in
# HR.LOADGEN (region = WEST or EAST). That keeps the two sides from conflicting.
set -euo pipefail

cd "$(dirname "$0")"

DBS=(db233demoW:WEST db233demoE:EAST)
HR_CONN='hr/"Welcome##123"@FREEPDB1'

sql() {   # sql <container> : runs stdin as HR in FREEPDB1
    docker exec -i "$1" sqlplus -s -L "$HR_CONN"
}

table_exists() {
    echo "set heading off feedback off pagesize 0
select count(*) from user_tables where table_name = 'LOADGEN';" | sql "$1" | tr -d '[:space:]'
}

ensure_table() {
    # DDL is replicated, so create the table on WEST only and let GoldenGate bring it to EAST.
    if [ "$(table_exists db233demoW)" != "1" ]; then
        echo "Creating HR.LOADGEN on WEST ..."
        sql db233demoW <<'SQL'
WHENEVER SQLERROR EXIT FAILURE
-- Each database numbers its own rows from 1, so the key must include region,
-- and the identity must accept the explicit IDs that the replicat inserts.
create table loadgen (
    region   varchar2(4)  not null,
    id       number generated by default on null as identity,
    payload  varchar2(200),
    counter  number default 0 not null,
    created  timestamp default systimestamp not null,
    updated  timestamp,
    constraint loadgen_pk primary key (region, id)
);
SQL
    fi
    for i in $(seq 1 30); do
        [ "$(table_exists db233demoE)" = "1" ] && return 0
        sleep 2
    done
    echo "HR.LOADGEN did not replicate to EAST within 60 s; check replicat RWEST." >&2
    exit 1
}

steady() {   # steady <container> <region> <seconds> <rows/s>
    sql "$1" <<SQL
WHENEVER SQLERROR EXIT FAILURE
set feedback off
declare
    stop_at  timestamp := systimestamp + numtodsinterval($3, 'SECOND');
    tick     timestamp;
    rows_ps  pls_integer := greatest(3, $4);
begin
    dbms_application_info.set_module('loadgen', '$2 steady');
    while systimestamp < stop_at loop
        tick := systimestamp;
        -- per second: ~1/2 inserts, ~1/3 updates, the rest deletes of the oldest rows
        for i in 1 .. ceil(rows_ps / 2) loop
            insert into loadgen (region, payload)
            values ('$2', dbms_random.string('a', 100));
        end loop;
        update loadgen
           set counter = counter + 1, updated = systimestamp
         where region = '$2'
           and id in (select id from loadgen where region = '$2'
                      order by dbms_random.value fetch first ceil(rows_ps / 3) rows only);
        delete from loadgen
         where region = '$2'
           and id in (select id from loadgen where region = '$2'
                      order by id fetch first (rows_ps - ceil(rows_ps / 2) - ceil(rows_ps / 3)) rows only)
           and (select count(*) from loadgen where region = '$2') > rows_ps * 30;
        commit;
        dbms_session.sleep(greatest(0, 1 - extract(second from (systimestamp - tick))));
    end loop;
end;
/
SQL
}

burst() {   # burst <rows> : one big transaction on WEST
    echo "Burst: inserting $1 rows on WEST in one transaction, then deleting them in another ..."
    sql db233demoW <<SQL
WHENEVER SQLERROR EXIT FAILURE
set feedback off
begin
    dbms_application_info.set_module('loadgen', 'WEST burst');
    for i in 1 .. $1 loop
        insert into loadgen (region, payload) values ('BRST', dbms_random.string('a', 100));
    end loop;
    commit;
    delete from loadgen where region = 'BRST';
    commit;
end;
/
SQL
    echo "Burst done."
}

stop_load() {
    for entry in "${DBS[@]}"; do
        docker exec -i "${entry%%:*}" sqlplus -s / as sysdba <<'SQL'
set feedback off serveroutput on
begin
    for s in (select sid, serial#, con_id from v$session where module = 'loadgen') loop
        execute immediate 'alter system kill session ''' || s.sid || ',' || s.serial# || ''' immediate';
        dbms_output.put_line('killed session ' || s.sid);
    end loop;
end;
/
SQL
    done
}

case "${1:-}" in
    stop)
        stop_load
        ;;
    burst)
        ensure_table
        burst "${2:-20000}"
        ;;
    ""|[0-9]*)
        seconds=${1:-600}
        rate=${2:-50}
        ensure_table
        echo "Steady load: $rate rows/s on WEST and EAST for $seconds s (Ctrl-C or ./load.sh stop to end) ..."
        trap 'stop_load; exit 130' INT TERM
        pids=()
        for entry in "${DBS[@]}"; do
            steady "${entry%%:*}" "${entry##*:}" "$seconds" "$rate" & pids+=($!)
        done
        wait "${pids[@]}"
        echo "Steady load finished."
        ;;
    *)
        sed -n '2,8p' "$0"
        exit 1
        ;;
esac
